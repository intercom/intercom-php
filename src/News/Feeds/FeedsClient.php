    /**
     * You can fetch a list of all news items that are live on a given newsfeed
     *
     * Example:
     * ```php
     * $client->news->feeds->listItems(
     *     new ListNewsFeedItemsRequest([
     *         'newsfeedId' => '123',
     *     ]),
     * );
     * ```
     *
     * @param ListNewsFeedItemsRequest $request
